/** All land cells as { col, row } — computed once. */
export const LAND_CELLS = ROWS.flatMap((runs, row) => {
  const cols = new Set()
  runs.forEach(([a, b]) => { for (let c = a; c <= b; c++) cols.add(c) })
  return [...cols].map((col) => ({ col, row }))
})

/** Project lon/lat into the same grid space (fractional col/row). */
export function project(lon, lat) {
  return { col: (lon + 180) / 5, row: (80 - lat) / 5 }
}
